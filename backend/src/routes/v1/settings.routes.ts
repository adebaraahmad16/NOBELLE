import { Router } from 'express';
import { z } from 'zod';
import multer from 'multer';
import { action } from '../../controllers/customer.controller';
import { SettingsService } from '../../services/settings.service';
import { SettingsAssetService } from '../../services/settingsAsset.service';
import { adminAuthMiddleware } from '../../middleware/adminAuth.middleware';
import { rateLimit } from '../../middleware/rateLimit.middleware';
import { type SettingsSection, profileSchema,passwordSchema,zoneSchema,staffSchema,policySchema,DEFAULT_SETTINGS } from '../../validators/settings.validator';
import { ApiError } from '../../utils/apiError';
const router=Router();
router.use(adminAuthMiddleware());
router.get('/settings/config',action(req=>SettingsService.root(req.admin!.id)));
router.patch('/settings/account',action(req=>SettingsService.profile(req.admin!.id,req.body),profileSchema));
router.post('/settings/account/password',rateLimit(10,15*60_000),action(req=>SettingsService.changePassword(req.admin!.id,req.admin!.sid!,req.body),passwordSchema));
router.get('/settings/security',action(req=>SettingsService.security(req.admin!.id,req.admin!.sid!)));
router.delete('/settings/security/sessions',action(req=>SettingsService.revokeSessions(req.admin!.id,req.admin!.sid!)));
router.delete('/settings/security/sessions/:id',action(req=>SettingsService.revokeSessions(req.admin!.id,req.admin!.sid!,req.params.id)));
const images=multer({storage:multer.memoryStorage(),limits:{fileSize:5*1024*1024,files:1}});
router.post('/settings/assets/:kind',images.single('image'),action(req=>SettingsAssetService.upload(req.file,req.params.kind)));
router.get('/settings/shipping/zones',action(()=>SettingsService.zones()));
router.post('/settings/shipping/zones',action(req=>SettingsService.saveZone(undefined,req.body),zoneSchema));
router.patch('/settings/shipping/zones/:id',action(req=>SettingsService.saveZone(req.params.id,req.body),zoneSchema));
router.delete('/settings/shipping/zones/:id',action(req=>SettingsService.removeZone(req.params.id)));
router.get('/settings/policies',action(()=>SettingsService.policies()));
router.patch('/settings/policies/:id',action(req=>SettingsService.savePolicy(req.params.id,req.body),policySchema));
router.get('/settings/staff',action(()=>SettingsService.staff()));
router.post('/settings/staff',action(req=>SettingsService.saveStaff(req.admin!.id,req.admin!.adminRole!,undefined,req.body),staffSchema));
router.patch('/settings/staff/:id',action(req=>SettingsService.saveStaff(req.admin!.id,req.admin!.adminRole!,req.params.id,req.body),staffSchema));
router.delete('/settings/staff/:id',action(req=>SettingsService.removeStaff(req.admin!.id,req.admin!.adminRole!,req.params.id)));
const envelope=z.object({values:z.unknown(),version:z.string().max(100).nullable().optional()}).strict();
router.patch('/settings/:section',action(req=>SettingsService.save(req.params.section as SettingsSection,req.body.values,req.body.version,req.admin!.adminRole!),envelope));
router.post('/settings/:section/reset',action(req=>{const section=req.params.section as SettingsSection;if(!DEFAULT_SETTINGS[section])throw ApiError.notFound('Settings section not found');return SettingsService.save(section,DEFAULT_SETTINGS[section],req.body.version,req.admin!.adminRole!);},z.object({version:z.string().max(100).nullable().optional()}).strict()));
export default router;
