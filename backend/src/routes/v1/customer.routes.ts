import { z } from 'zod';
import prisma from '../../repositories/prisma';
import { action } from '../../controllers/customer.controller';
import { Router } from 'express';
import { CustomerController as C } from '../../controllers/customer.controller';
import { authMiddleware } from '../../middleware/auth.middleware';
const router = Router();
router.post('/contact', C.contact);
router.get('/delivery-zones', C.delivery);
router.post('/newsletter', action(req => prisma.newsletterSubscriber.upsert({ where: { email: req.body.email.toLowerCase() }, create: { email: req.body.email.toLowerCase() }, update: { isActive: true } }), z.object({ email: z.string().email() })));
router.use(authMiddleware);
router.patch('/profile', C.profile);
router.patch('/profile/password', C.password);
router.get('/addresses', C.addresses);
router.post('/addresses', C.saveAddress);
router.patch('/addresses/:id', C.saveAddress);
router.delete('/addresses/:id', C.deleteAddress);
router.get('/wishlist', C.wishlist);
router.post('/wishlist/:productId', C.addWishlist);
router.delete('/wishlist/:productId', C.removeWishlist);
router.post('/products/:productId/reviews', C.review);
router.get('/returns', C.returns);
router.post('/returns', C.requestReturn);
router.get('/notifications', C.notifications);
router.patch('/notifications/read-all', C.readNotification);
router.patch('/notifications/:id/read', C.readNotification);
export default router;
