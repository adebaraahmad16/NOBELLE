import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { createDatabase,applyMigrations,readContract } from '../tests/supabase-fixture.mjs';

const literal=value=>`'${value.replaceAll("'","''")}'`;
export function buildAudit(contract){
 const values=Object.entries(contract).map(([name,table])=>` (${literal(name)},array[${table.columns.map(c=>literal(c.name)).join(',')}])`).join(',\n');
 const constraints=Object.entries(contract).flatMap(([name,table])=>table.constraints.map(c=>` (${literal(name)},${literal(c.name)},${literal(c.definition)})`)).join(',\n');
 const indexes=Object.entries(contract).flatMap(([name,table])=>table.indexes.map(c=>` (${literal(name)},${literal(c.name)},${literal(c.definition)})`)).join(',\n');
 const columns=Object.entries(contract).flatMap(([name,table])=>table.columns.map(c=>` (${literal(name)},${literal(c.name)},${literal(c.type)},${c.required})`)).join(',\n');
 return `-- GENERATED by npm run build:database-audit. Read-only SQL-editor audit.
-- No application data is read or changed. Run before selecting an install path.
with expected(table_name,columns) as (values\n${values}\n)
select e.table_name,c.oid is not null as table_exists,
 array(select name from unnest(e.columns) name where not exists(select 1 from pg_attribute a where a.attrelid=c.oid and a.attname=name and not a.attisdropped)) missing_columns,
 c.relrowsecurity as rls_enabled,
 case when c.oid is not null then has_table_privilege('anon',c.oid,'SELECT') end anon_select_grant,
 case when c.oid is not null then has_table_privilege('authenticated',c.oid,'SELECT') end authenticated_select_grant,
 exists(select 1 from pg_publication_tables p where p.pubname='supabase_realtime' and p.schemaname='public' and p.tablename=e.table_name) realtime_enabled
from expected e left join pg_class c on c.oid=to_regclass(format('public.%I',e.table_name)) order by e.table_name;

-- All foreign keys, primary/unique keys and checks must be validated. A matching
-- constraint with a different name is accepted; existing data is never deleted.
with expected(table_name,name,definition) as (values\n${constraints}\n)
select e.table_name,e.name expected_name,e.definition,
 exists(select 1 from pg_constraint c where c.conrelid=to_regclass(format('public.%I',e.table_name)) and pg_get_constraintdef(c.oid)=e.definition and c.convalidated) as constraint_present
from expected e order by e.table_name,e.name;

with expected(table_name,name,definition) as (values\n${indexes}\n)
select e.*,exists(select 1 from pg_indexes i where i.schemaname='public' and i.tablename=e.table_name and regexp_replace(i.indexdef,'(INDEX )("[^"]+"|[^ ]+)( ON )','\\1\\3')=regexp_replace(e.definition,'(INDEX )("[^"]+"|[^ ]+)( ON )','\\1\\3')) as index_present
from expected e order by e.table_name,e.name;

with expected(table_name,column_name,expected_type,required) as (values\n${columns}\n)
select e.*,format_type(a.atttypid,a.atttypmod) actual_type,
 (format_type(a.atttypid,a.atttypmod)=e.expected_type or e.table_name='store_settings' and e.column_name='id' and format_type(a.atttypid,a.atttypmod) in ('smallint','integer','bigint')) as type_matches,
 (not e.required or a.attnotnull) as nullability_matches
from expected e left join pg_attribute a on a.attrelid=to_regclass(format('public.%I',e.table_name)) and a.attname=e.column_name and not a.attisdropped
order by e.table_name,e.column_name;

select tablename,policyname,roles,cmd,qual,with_check from pg_policies
where schemaname='public' and tablename in (select table_name from information_schema.tables where table_schema='public')
order by tablename,policyname;

-- Detect naming drift without renaming columns or altering existing records.
select table_name,column_name,data_type from information_schema.columns
where table_schema='public' and column_name in ('createdAt','updatedAt','isActive','created_at','updated_at','is_active')
order by table_name,column_name;
select name dependency,to_regclass(name) is not null dependency_exists from unnest(array['auth.users','auth.sessions','storage.buckets','storage.objects','private.rate_limits']) name;
-- Application columns use quoted "createdAt"/"isActive"; auth.sessions uses
-- Supabase-owned created_at/updated_at. Do not rename Supabase Auth columns.
-- customers is an admin resource backed by profiles, not a second user table.
-- If objects exist but PostgREST returns PGRST205, check exposed schemas/grants,
-- then run the separate migration containing NOTIFY pgrst, 'reload schema'.
`;
}
export async function buildArtifacts(){
 const db=await createDatabase();
 try{
  await applyMigrations(db);
  const contract=await readContract(db);
  writeFileSync('supabase/database-contract.json',JSON.stringify(contract,null,2)+'\n');
  writeFileSync('supabase/diagnostics.sql',buildAudit(contract));
  console.log(`Generated complete schema audit: ${Object.keys(contract).length} tables, ${Object.values(contract).reduce((n,t)=>n+t.constraints.length,0)} constraints, ${Object.values(contract).reduce((n,t)=>n+t.indexes.length,0)} indexes. No hosted database was changed.`);
 }finally{await db.close();}
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){try{await buildArtifacts();}catch(error){console.error('Database audit build failed:',error.code||'',error.message);process.exitCode=1;}}
